package br.com.mytrace.printer_client.core;

public class ImpressoraDTO {

	private Integer idImpressora;
	private String dsImpressora;
	private String dsNumeroSerie;
	private Integer idPrograma;
	private String dsPrograma;

	public Integer getIdImpressora() {
		return idImpressora;
	}

	public void setIdImpressora(Integer idImpressora) {
		this.idImpressora = idImpressora;
	}

	public String getDsImpressora() {
		return dsImpressora;
	}

	public void setDsImpressora(String dsImpressora) {
		this.dsImpressora = dsImpressora;
	}

	public String getDsNumeroSerie() {
		return dsNumeroSerie;
	}

	public void setDsNumeroSerie(String dsNumeroSerie) {
		this.dsNumeroSerie = dsNumeroSerie;
	}

	public Integer getIdPrograma() {
		return idPrograma;
	}

	public void setIdPrograma(Integer idPrograma) {
		this.idPrograma = idPrograma;
	}

	public String getDsPrograma() {
		return dsPrograma;
	}

	public void setDsPrograma(String dsPrograma) {
		this.dsPrograma = dsPrograma;
	}

}
